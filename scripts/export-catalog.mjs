import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

const sourceUrl = new URL('../data/catalog.json', import.meta.url);
const runtimeUrl = new URL('../catalog-service.js', import.meta.url);
const outputUrl = new URL('../catalog-data.js', import.meta.url);
const catalog = JSON.parse(await readFile(sourceUrl, 'utf8'));
const runtimeSource = await readFile(runtimeUrl, 'utf8');

if (catalog.schemaVersion !== 1) throw new Error(`Unsupported catalogue schema version: ${catalog.schemaVersion}`);
const sandboxWindow = { STARMUSICS_CATALOG_SOURCE: catalog, location: { origin: 'https://starmusics.invalid' } };
vm.runInNewContext(runtimeSource, { window: sandboxWindow, URL }, { timeout: 1000, filename: 'catalog-service.js' });
const report = sandboxWindow.STARMUSICS_CatalogRuntime.validate(catalog);
if (!report.valid) throw new Error(`Refusing to export invalid catalogue:\n- ${report.errors.join('\n- ')}`);

const generated = `/* Generated from data/catalog.json by npm run build:catalog. Do not edit this file directly. */\nwindow.STARMUSICS_CATALOG_SOURCE = ${JSON.stringify(catalog, null, 2)};\n`;
await writeFile(outputUrl, generated);
console.log(`Generated catalog-data.js from data/catalog.json (${catalog.tracks.length} tracks, ${catalog.artists.length} artists, ${catalog.albums.length} albums).`);
